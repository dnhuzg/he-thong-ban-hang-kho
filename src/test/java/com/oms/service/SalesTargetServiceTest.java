package com.oms.service;

import com.oms.config.Db;
import com.oms.model.Role;
import com.oms.model.SalesTarget;
import com.oms.model.User;
import com.oms.support.DatabaseTest;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.sql.Connection;
import java.time.LocalDate;

import static org.junit.jupiter.api.Assertions.*;

class SalesTargetServiceTest extends DatabaseTest {

    private final SalesTargetService service = new SalesTargetService();

    private User manager;
    private User employee;
    private User otherEmployee;

    private final LocalDate currentMonth =
            LocalDate.now().withDayOfMonth(1);

    @BeforeEach
    void fixture() throws Exception {
        sql("""
            CREATE TABLE IF NOT EXISTS sales_targets (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                employee_id BIGINT NOT NULL REFERENCES users(id),
                area_id BIGINT NOT NULL REFERENCES areas(id),
                target_month DATE NOT NULL,
                target_amount DECIMAL(18,2) NOT NULL,
                created_by BIGINT REFERENCES users(id),
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                UNIQUE(employee_id, area_id, target_month)
            )
            """);

        manager = user("target_manager", Role.SALES_MANAGER);
        employee = user("target_employee", Role.SALES_REP);
        otherEmployee = user("target_other", Role.SALES_REP);

        sql("INSERT INTO user_areas(user_id, area_id) " +
            "SELECT " + employee.getId() + ",30 " +
            "WHERE NOT EXISTS (SELECT 1 FROM user_areas " +
            "WHERE user_id=" + employee.getId() +
            " AND area_id=30)");
    }

    private SalesTarget target(LocalDate month, String amount) {
        SalesTarget t = new SalesTarget();
        t.setEmployeeId(employee.getId());
        t.setAreaId(30);
        t.setTargetMonth(month);
        t.setTargetAmount(new BigDecimal(amount));
        return t;
    }

    @Test
    void ac1ManagerCanCreateMonthlyTarget() throws Exception {
        LocalDate month = currentMonth.plusMonths(1);

        long id = service.create(target(month, "10000000"), manager);

        assertTrue(id > 0);
        assertTrue(service.listByMonth(month, manager).stream()
                .anyMatch(t -> t.getId() == id
                        && t.getEmployeeId() == employee.getId()
                        && t.getAreaId() == 30
                        && t.getTargetAmount()
                            .compareTo(new BigDecimal("10000000")) == 0));
    }

    @Test
    void ac1EmployeeCannotSetTarget() {
        assertThrows(ForbiddenException.class,
                () -> service.create(
                        target(currentMonth.plusMonths(1), "10000000"),
                        employee));
    }

    @Test
    void ac2EmployeeCanReadOwnTargetButNotOthersProgress()
            throws Exception {

        long id = service.create(
                target(currentMonth, "10000000"), manager);

        assertTrue(service.myTargets(employee).stream()
                .anyMatch(t -> t.getId() == id));

        assertTrue(service.myTargets(otherEmployee).stream()
                .noneMatch(t -> t.getId() == id));

        var progress = service.progress(id, employee);

        assertEquals(id, progress.target().getId());
        assertEquals(0, new BigDecimal("10000000")
                .compareTo(progress.target().getTargetAmount()));

        assertThrows(ForbiddenException.class,
                () -> service.progress(id, otherEmployee));
    }

    @Test
    void ac2ProgressCalculatesActualInvoiceRevenue()
            throws Exception {

        long id = service.create(
                target(currentMonth, "1000000"), manager);

        sql("INSERT INTO products(id,sku,name,category_id,base_unit_id,cost_price,status) " +
            "VALUES(9901,'AC2-PRODUCT','AC2 Product',3,1,1000,'ACTIVE')");

        sql("INSERT INTO customers(id,code,name,group_id,area_id,sales_rep_id) " +
            "VALUES(9901,'AC2-CUSTOMER','AC2 Customer',1,30," +
            employee.getId() + ")");

        String issuedAt = currentMonth + " 09:00:00";

        sql("INSERT INTO invoices(id,code,customer_id,total_amount,paid_amount,issued_at,due_date,status) " +
            "VALUES(9901,'AC2-INV-1',9901,300000,0,'" +
            issuedAt + "','" + currentMonth + "','ISSUED')");

        sql("INSERT INTO invoice_lines(invoice_id,product_id,quantity,unit_price,amount) " +
            "VALUES(9901,9901,3,100000,300000)");

        sql("INSERT INTO invoices(id,code,customer_id,total_amount,paid_amount,issued_at,due_date,status) " +
            "VALUES(9902,'AC2-INV-2',9901,900000,0,'" +
            issuedAt + "','" + currentMonth + "','CANCELLED')");

        sql("INSERT INTO invoice_lines(invoice_id,product_id,quantity,unit_price,amount) " +
            "VALUES(9902,9901,9,100000,900000)");

        var progress = service.progress(id, employee);

        assertEquals(0, new BigDecimal("300000")
                .compareTo(progress.revenue()));

        assertEquals(0, new BigDecimal("30")
                .compareTo(progress.percentage()));
    }
    @Test
    void ac3PastTargetRequiresReasonAndCreatesAuditLog()
            throws Exception {

        LocalDate past = currentMonth.minusMonths(1);

        sql("INSERT INTO sales_targets(" +
            "employee_id,area_id,target_month,target_amount,created_by" +
            ") VALUES(" + employee.getId() +
            ",30,'" + past + "',10000000," +
            manager.getId() + ")");

        long id;
        try (Connection conn = Db.getConnection();
             var ps = conn.prepareStatement(
                     "SELECT id FROM sales_targets " +
                     "WHERE employee_id=? AND target_month=?")) {
            ps.setLong(1, employee.getId());
            ps.setDate(2, java.sql.Date.valueOf(past));

            try (var rs = ps.executeQuery()) {
                assertTrue(rs.next());
                id = rs.getLong(1);
            }
        }

        assertThrows(ServiceException.class,
                () -> service.update(
                        id, new BigDecimal("12000000"), "", manager));

        service.update(
                id, new BigDecimal("12000000"),
                "Dieu chinh theo phe duyet", manager);

        try (Connection conn = Db.getConnection();
             var ps = conn.prepareStatement(
                     "SELECT target_amount FROM sales_targets WHERE id=?")) {
            ps.setLong(1, id);

            try (var rs = ps.executeQuery()) {
                assertTrue(rs.next());
                assertEquals(0, new BigDecimal("12000000")
                        .compareTo(rs.getBigDecimal(1)));
            }
        }

        try (Connection conn = Db.getConnection();
             var ps = conn.prepareStatement(
                     "SELECT COUNT(*) FROM audit_logs " +
                     "WHERE target_type='SALES_TARGET' " +
                     "AND target_id=? AND detail LIKE ?")) {
            ps.setLong(1, id);
            ps.setString(2, "%Dieu chinh theo phe duyet%");

            try (var rs = ps.executeQuery()) {
                assertTrue(rs.next());
                assertTrue(rs.getLong(1) > 0,
                        "Phai ghi nhat ky kem ly do sua");
            }
        }
    }
}